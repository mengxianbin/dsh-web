#!/usr/bin/env node
/**
 * client - a dependency-free protocol v1 client for dsh-remote-bridge.
 *
 * Sequence mode drives the frozen v1 flow and prints every frame so the whole
 * transcript can be pasted into a report:
 *
 *   hello -> session.list -> session.snapshot -> session.prompt -> session.delta
 *
 * It stops once three session.delta events have arrived or a turn-end delta
 * does. The script is a protocol client and nothing else: it never calls a
 * model on its own, and it holds no protocol logic beyond the wire format.
 *
 * Pair mode mints a bootstrap token over loopback and pairs a throwaway local
 * P-256 key from node:crypto, so a test machine without a Secure Enclave can
 * obtain a device token.
 *
 * Usage:
 *   BRIDGE_URL=ws://127.0.0.1:3080/ios/v1 BRIDGE_TOKEN=<deviceToken> \
 *     node scripts/client.mjs
 *   node scripts/client.mjs --pair --pair-base http://127.0.0.1:3080
 *
 * Run with --help for the full option list.
 *
 * Node >= 22: the global WebSocket, global fetch and Buffer base64url codec
 * are all this script needs; it has no package dependency and imports only
 * node:crypto.
 */
import { generateKeyPairSync, sign as signWithKey } from 'node:crypto'

const PROTOCOL_VERSION = 1
const PROTOCOL_MINOR = 0
const CLIENT_NAME = 'ios/0.1'
const CLIENT_CAPABILITY = 'session.stream.v1'
const DEFAULT_PROMPT = 'Protocol v1 client check: reply with one short sentence.'
const DEFAULT_WS_PATH = '/ios/v1'
const TOKEN_PATH = '/remote-bridge/pair/token'
const DEFAULT_TIMEOUT_MS = 15000
const DEFAULT_DELTA_TIMEOUT_MS = 90000
const EXIT_OK = 0
const EXIT_FAILURE = 1
const EXIT_USAGE = 2

const HELP = `client.mjs - dependency-free protocol v1 client for dsh-remote-bridge

Usage:
  node scripts/client.mjs [options]
  node scripts/client.mjs --pair [options]

Sequence mode runs hello -> session.list -> session.snapshot -> session.prompt
and then waits for session.delta until three events or one turn-end arrived.
Every frame is printed as it crosses the socket: "→" for frames this script
sends, "←" for frames it receives. Events carry an arrival number
("← #3 {...}") so a transcript is easy to reference in a report.

Pair mode (--pair) is for test machines without a Secure Enclave: it mints a
bootstrap token over loopback, pairs a throwaway P-256 key generated by
node:crypto, and prints the resulting deviceToken.

Options:
  --url <ws-url>              bridge WebSocket URL, e.g. ws://127.0.0.1:3080${DEFAULT_WS_PATH}
                              (env BRIDGE_URL; required unless --pair gets one from the token response)
  --token <token>             device token (env BRIDGE_TOKEN)
  --token-query               carry the token as ?token= instead of the Authorization header
  --session <sessionId>       session to snapshot and prompt (default: the first session in session.list)
  --text <prompt>             prompt text (default: "${DEFAULT_PROMPT}")
  --timeout <ms>              per-request timeout (default ${DEFAULT_TIMEOUT_MS})
  --delta-timeout <ms>        how long to wait for session.delta (default ${DEFAULT_DELTA_TIMEOUT_MS})
  --pair                      mint a bootstrap token and pair a throwaway key, then exit
  --pair-base <http-url>      HTTP base for GET ${TOKEN_PATH} (env BRIDGE_HTTP;
                              default: derived from --url)
  --pair-nonce-encoding <e>   bytes signed in pair.finish: base64url | utf8 (default:
                              base64url, then utf8 on a signature-invalid retry)
  -h, --help                  print this help and exit 0

Exit codes:
  0  the requested flow finished
  1  transport, protocol or pairing failure
  2  usage error (unknown option, missing value, missing required input)
`

class UsageError extends Error {}

class ProtocolError extends Error {
  constructor(code, message) {
    super(`${code}${message ? ': ' + message : ''}`)
    this.name = 'ProtocolError'
    this.code = code
  }
}

function note(text) {
  process.stdout.write('note: ' + text + '\n')
}

function warn(text) {
  process.stderr.write('client: ' + text + '\n')
}

function printFrame(direction, text) {
  process.stdout.write(direction + ' ' + text + '\n')
}

function takeValue(argv, index, name, inline) {
  if (inline !== undefined) return { value: inline, next: index }
  const next = argv[index + 1]
  if (next === undefined) throw new UsageError('missing value for ' + name)
  return { value: next, next: index + 1 }
}

function parseArgs(argv) {
  const opts = {
    url: process.env.BRIDGE_URL || '',
    token: process.env.BRIDGE_TOKEN || '',
    tokenQuery: false,
    session: '',
    text: DEFAULT_PROMPT,
    timeoutMs: DEFAULT_TIMEOUT_MS,
    deltaTimeoutMs: DEFAULT_DELTA_TIMEOUT_MS,
    pair: false,
    pairBase: process.env.BRIDGE_HTTP || '',
    nonceEncoding: '',
    help: false,
  }
  for (let i = 0; i < argv.length; i++) {
    const raw = argv[i]
    if (!raw.startsWith('-')) throw new UsageError('unexpected argument: ' + raw)
    const eq = raw.indexOf('=')
    const name = eq >= 0 ? raw.slice(0, eq) : raw
    const inline = eq >= 0 ? raw.slice(eq + 1) : undefined
    const read = () => {
      const taken = takeValue(argv, i, name, inline)
      i = taken.next
      return taken.value
    }
    switch (name) {
      case '-h':
      case '--help':
        opts.help = true
        break
      case '--url':
        opts.url = read()
        break
      case '--token':
        opts.token = read()
        break
      case '--token-query':
        opts.tokenQuery = true
        break
      case '--session':
        opts.session = read()
        break
      case '--text':
        opts.text = read()
        break
      case '--timeout':
        opts.timeoutMs = Number(read())
        break
      case '--delta-timeout':
        opts.deltaTimeoutMs = Number(read())
        break
      case '--pair':
        opts.pair = true
        break
      case '--pair-base':
        opts.pairBase = read()
        break
      case '--pair-nonce-encoding':
        opts.nonceEncoding = read()
        break
      default:
        throw new UsageError('unknown option: ' + name)
    }
  }
  for (const [label, value] of [['--timeout', opts.timeoutMs], ['--delta-timeout', opts.deltaTimeoutMs]]) {
    if (!Number.isFinite(value) || value <= 0) throw new UsageError(`${label} needs a positive number of milliseconds`)
  }
  if (!['', 'utf8', 'base64url'].includes(opts.nonceEncoding)) {
    throw new UsageError('--pair-nonce-encoding must be base64url or utf8')
  }
  return opts
}

function withTimeout(promise, ms, label) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`timeout after ${ms} ms waiting for ${label}`)), ms)
    promise.then(
      (value) => {
        clearTimeout(timer)
        resolve(value)
      },
      (error) => {
        clearTimeout(timer)
        reject(error)
      },
    )
  })
}

/** One bridge connection: frame printing, request/response correlation, events. */
class Bridge {
  constructor(socket) {
    this.socket = socket
    this.pending = new Map()
    this.listeners = new Set()
    this.nextId = 1
    this.eventCount = 0
    socket.addEventListener('message', (event) => this.onMessage(event.data))
    socket.addEventListener('close', () => {
      for (const pending of this.pending.values()) {
        pending.reject(new Error('socket closed before the response arrived'))
      }
      this.pending.clear()
    })
  }

  send(frame) {
    const text = JSON.stringify(frame)
    printFrame('→', text)
    this.socket.send(text)
  }

  request(method, params) {
    const id = this.nextId++
    const promise = new Promise((resolve, reject) => {
      this.pending.set(id, { resolve, reject })
    })
    this.send({ t: 'req', id, m: method, p: params ?? {} })
    return promise
  }

  onEvent(listener) {
    this.listeners.add(listener)
    return () => this.listeners.delete(listener)
  }

  onMessage(data) {
    const raw = typeof data === 'string' ? data : Buffer.from(data).toString('utf8')
    let frame
    try {
      frame = JSON.parse(raw)
    } catch {
      note('ignoring an unparsable frame: ' + raw.slice(0, 200))
      return
    }
    if (frame.t === 'ping') {
      this.send({ t: 'pong', ts: Date.now() })
      return
    }
    if (frame.t === 'ev') {
      this.eventCount += 1
      printFrame('←', '#' + this.eventCount + ' ' + raw)
      for (const listener of [...this.listeners]) listener(frame)
      return
    }
    printFrame('←', raw)
    if (frame.t !== 'res') return
    const pending = this.pending.get(frame.id)
    if (!pending) {
      note('response for unknown request id ' + frame.id)
      return
    }
    this.pending.delete(frame.id)
    if (frame.ok) pending.resolve(frame.r)
    else pending.reject(new ProtocolError(frame.e?.code ?? 'unknown-error', frame.e?.msg ?? ''))
  }
}

function openSocket(url, headers, timeoutMs) {
  return new Promise((resolve, reject) => {
    const socket = headers ? new WebSocket(url, { headers }) : new WebSocket(url)
    const timer = setTimeout(() => {
      try {
        socket.close()
      } catch {
        /* the handshake already failed */
      }
      reject(new Error(`timeout after ${timeoutMs} ms opening ${url}`))
    }, timeoutMs)
    socket.addEventListener('open', () => {
      clearTimeout(timer)
      resolve(socket)
    })
    socket.addEventListener('error', () => {
      clearTimeout(timer)
      reject(new Error('websocket error opening ' + url + ' (is the bridge mounted on that host and port?)'))
    })
  })
}

function httpBaseOf(wsUrl) {
  const url = new URL(wsUrl)
  url.protocol = url.protocol === 'wss:' ? 'https:' : 'http:'
  url.pathname = ''
  url.search = ''
  url.hash = ''
  return url.origin
}

function wsUrlOf(httpBase) {
  const url = new URL(httpBase)
  url.protocol = url.protocol === 'https:' ? 'wss:' : 'ws:'
  url.pathname = DEFAULT_WS_PATH
  url.search = ''
  url.hash = ''
  return url.toString()
}

/** Attach the device token: Authorization header first, ?token= only on request. */
function authenticatedUrl(opts, url) {
  if (!opts.token || !opts.tokenQuery) return url
  const target = new URL(url)
  target.searchParams.set('token', opts.token)
  return target.toString()
}

function authHeaders(opts) {
  if (!opts.token || opts.tokenQuery) return undefined
  return { authorization: 'Bearer ' + opts.token }
}

async function runSequence(opts) {
  if (!opts.url) throw new UsageError('no bridge URL: pass --url <ws-url> or set BRIDGE_URL')
  if (!opts.token) {
    warn('no device token (BRIDGE_TOKEN / --token): the connection will be unpaired and only hello will succeed')
  } else if (opts.tokenQuery) {
    warn('carrying the device token as ?token= in the URL (--token-query): the query string is visible to the relay and access logs')
  }
  const url = authenticatedUrl(opts, opts.url)
  note('connecting to ' + url)
  const socket = await openSocket(url, authHeaders(opts), opts.timeoutMs)
  const bridge = new Bridge(socket)
  try {
    const hello = await withTimeout(
      bridge.request('hello', {
        proto: PROTOCOL_VERSION,
        minor: PROTOCOL_MINOR,
        client: CLIENT_NAME,
        cap: [CLIENT_CAPABILITY],
      }),
      opts.timeoutMs,
      'hello',
    )
    note(`hello: server=${hello.server} auth=${hello.auth} resume=${hello.resume} proto=${hello.proto}.${hello.minor}`)
    if (hello.auth !== 'paired') {
      note('unpaired connection: only hello, pair.begin and pair.finish are allowed - run --pair or pass a device token')
    }

    const list = await withTimeout(bridge.request('session.list', {}), opts.timeoutMs, 'session.list')
    const sessions = Array.isArray(list.sessions) ? list.sessions : []
    note('session.list: ' + sessions.length + ' session(s)')
    const sessionId = opts.session || sessions[0]?.id
    if (!sessionId) {
      throw new Error('no session to talk to: open one in the Web GUI or pass --session <sessionId>')
    }
    note('using sessionId=' + sessionId)

    const snapshot = await withTimeout(
      bridge.request('session.snapshot', { sessionId }),
      opts.timeoutMs,
      'session.snapshot',
    )
    const turns = Array.isArray(snapshot.turns) ? snapshot.turns : []
    note(`session.snapshot: lastSeq=${snapshot.lastSeq} turns=${turns.length} (lastSeq is the DSH cursor, not this connection's event seq)`)

    const deltas = []
    const settled = new Promise((resolve) => {
      bridge.onEvent((frame) => {
        if (frame.m !== 'session.delta' || frame.p?.sessionId !== sessionId) return
        deltas.push(frame)
        if (deltas.length >= 3 || frame.p.kind === 'turn-end') resolve()
      })
    })

    const requestId = 'client-' + Date.now().toString(36)
    await withTimeout(
      bridge.request('session.prompt', { sessionId, text: opts.text, requestId }),
      opts.timeoutMs,
      'session.prompt',
    )
    await withTimeout(settled, opts.deltaTimeoutMs, 'session.delta events')
    const kinds = deltas.map((frame) => frame.p.kind).join(', ')
    note(`collected ${deltas.length} session.delta event(s): ${kinds}`)
    note('sequence complete')
  } finally {
    try {
      socket.close()
    } catch {
      /* already closed */
    }
  }
}

async function fetchBootstrapToken(opts) {
  const base = opts.pairBase || (opts.url ? httpBaseOf(opts.url) : '')
  if (!base) {
    throw new UsageError('--pair needs --pair-base <http-url>, or --url to derive one from')
  }
  const endpoint = new URL(TOKEN_PATH, base).toString()
  note('GET ' + endpoint + ' (loopback only)')
  const response = await fetch(endpoint, { headers: { accept: 'application/json' } })
  const body = await response.text()
  printFrame('←', body.trim())
  if (!response.ok) {
    throw new Error(
      `the token endpoint answered HTTP ${response.status}; it is reachable from loopback only ` +
        '(403 means the request did not come from 127.0.0.1 / ::1 / ::ffff:127.0.0.1)',
    )
  }
  let payload
  try {
    payload = JSON.parse(body)
  } catch {
    throw new Error('the token endpoint did not answer JSON')
  }
  if (typeof payload.token !== 'string' || payload.token.length === 0) {
    throw new Error('the token response carried no token')
  }
  if (payload.expiresAt !== undefined) {
    const left = Number(payload.expiresAt) - Date.now()
    note(`bootstrap token valid for ${Number.isFinite(left) ? Math.max(0, Math.round(left / 1000)) : '?'} s (one use)`)
  }
  return payload
}

/** Sign the nonce and pair the key; each attempt spends one one-time token. */
async function attemptPair(opts, plan, socket, bridge) {
  const minted = await fetchBootstrapToken(opts)
  const begun = await withTimeout(bridge.request('pair.begin', { token: minted.token }), opts.timeoutMs, 'pair.begin')
  const nonce = String(begun.nonce ?? '')
  if (!nonce) throw new Error('pair.begin answered without a nonce')
  const signedBytes = plan.encoding === 'base64url' ? Buffer.from(nonce, 'base64url') : Buffer.from(nonce, 'utf8')
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'prime256v1' })
  // The host verifies the raw IEEE P1363 (r||s) shape and rejects anything whose
  // length is not exactly 64 bytes, so DER is never an option here.
  const signature = signWithKey('sha256', signedBytes, { key: privateKey, dsaEncoding: 'ieee-p1363' })
  const devicePubKey = publicKey.export({ type: 'spki', format: 'der' }).toString('base64url')
  note(`pairing attempt: ES256 over ${signedBytes.length} nonce bytes (${plan.encoding})`)
  const finished = await withTimeout(
    bridge.request('pair.finish', { devicePubKey, signature: signature.toString('base64url') }),
    opts.timeoutMs,
    'pair.finish',
  )
  return { minted, finished }
}

function pairPlan(opts) {
  const encodings = opts.nonceEncoding ? [opts.nonceEncoding] : ['base64url', 'utf8']
  return encodings.map(encoding => ({ encoding }))
}

async function runPair(opts) {
  const url = opts.url || wsUrlOf(opts.pairBase || 'http://127.0.0.1')
  note('connecting to ' + url)
  const socket = await openSocket(url, undefined, opts.timeoutMs)
  const bridge = new Bridge(socket)
  try {
    const hello = await withTimeout(
      bridge.request('hello', {
        proto: PROTOCOL_VERSION,
        minor: PROTOCOL_MINOR,
        client: CLIENT_NAME,
        cap: [CLIENT_CAPABILITY],
      }),
      opts.timeoutMs,
      'hello',
    )
    note(`hello: server=${hello.server} auth=${hello.auth} (pairing needs no device token)`)
    const plan = pairPlan(opts)
    const failures = []
    for (const [index, candidate] of plan.entries()) {
      try {
        const { finished } = await attemptPair(opts, candidate, socket, bridge)
        if (typeof finished.deviceToken !== 'string' || finished.deviceToken.length === 0) {
          throw new Error('pair.finish answered without a deviceToken')
        }
        note(`paired with ${candidate.encoding} nonce bytes; deviceId=${finished.deviceId}`)
        process.stdout.write('deviceToken: ' + finished.deviceToken + '\n')
        note(`reuse it with: BRIDGE_URL=${url} BRIDGE_TOKEN=${finished.deviceToken} node scripts/client.mjs`)
        return
      } catch (error) {
        if (!(error instanceof ProtocolError) || error.code !== 'signature-invalid') throw error
        failures.push(`${candidate.encoding}: ${error.code}`)
        if (index < plan.length - 1) note('signature rejected; retrying with the other nonce encoding')
      }
    }
    throw new Error('pairing failed for every signing convention tried: ' + failures.join('; '))
  } finally {
    try {
      socket.close()
    } catch {
      /* already closed */
    }
  }
}

async function main() {
  let opts
  try {
    opts = parseArgs(process.argv.slice(2))
  } catch (error) {
    warn(error.message)
    process.stderr.write('\n' + HELP)
    return EXIT_USAGE
  }
  if (opts.help) {
    process.stdout.write(HELP)
    return EXIT_OK
  }
  try {
    if (opts.pair) await runPair(opts)
    else await runSequence(opts)
    return EXIT_OK
  } catch (error) {
    if (error instanceof UsageError) {
      warn(error.message)
      return EXIT_USAGE
    }
    warn('failed: ' + (error instanceof Error ? error.message : String(error)))
    if (error instanceof ProtocolError && error.code === 'unpaired') {
      warn('the connection is unpaired: run --pair to mint a device token, or pass one with --token / BRIDGE_TOKEN')
    }
    return EXIT_FAILURE
  }
}

process.exitCode = await main()
