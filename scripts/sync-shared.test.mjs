test('header/strip round-trips every file kind', () => {
  for (const file of ['settings-form.ts', 'PluginSettingsCard.tsx', 'settings-card.module.css', 'SegmentGroup.tsx', 'RangeBubble.tsx']) {
    const source = 'export const x = 1' + String.fromCharCode(10)
    const sourceRel = 'shared/client/settings/' + file
    const rendered = renderCopy(source, file, sourceRel)
    assert.ok(rendered.startsWith(headerFor(file, sourceRel)))
    assert.equal(stripHeader(rendered, file, sourceRel), source)
    assert.equal(stripHeader('mangled ' + rendered.slice(10), file, sourceRel), undefined)
  }
})

test('copies cover the settings trio for all consumers plus host and http helpers', () => {
  // Normalize separators: node:path join yields backslashes on Windows, and
  // the copy-count buckets below match on forward slashes.
  const entries = copyEntries().map(entry => ({ ...entry, target: entry.target.replaceAll('\\', '/') }))
  // The total is every generated copy in the manifest; the single-instance
  // guard alone contributes one mount-once.ts per host half (20 today). The
  // buckets below partition the same set by target location. 163 = the 154
  // targets the manifest carried before the orphan sweep plus the 9 orphan
  // copies that sweep registered (sync-shared-orphan-probe-1128).
  assert.equal(entries.length, 163)
  const clientTrio = entries.filter(entry => entry.target.includes('/src/client/'))
  assert.equal(clientTrio.length, 74)
  const hostCopies = entries.filter(entry => entry.target.includes('/src/host/')
    || entry.target.includes('/src/dsh-home.ts')
    || entry.target.includes('/src/mount-once.ts')
    || entry.target.includes('/src/loopback.ts')
    || entry.target.includes('/src/pair-access.ts')
    || entry.target.includes('/src/agent/')
    || entry.target.endsWith('/packages/dsh-task-board/src/http.ts'))
  assert.equal(hostCopies.length, 71)
})

test('checkSync detects drift and applySync repairs it', async () => {
  const root = await mkdtemp(join(tmpdir(), 'sync-shared-test-'))
  try {
    // Fake tree: every shared source the manifest names, plus one consumer copy
    // whose content drifted. The sources are DERIVED from the manifest rather
    // than hand-listed: a hand-written list silently missed
    // shared/host/detached-work.ts when that entry was added, and checkSync
    // then died on ENOENT instead of reporting drift.
    const sourceText = 'export const shared = 1' + String.fromCharCode(10)
    const entries = copyEntries(root)
    for (const entry of entries) {
      await mkdir(dirname(entry.source), { recursive: true })
      await writeFile(entry.source, sourceText)
    }
    const targetDir = join(root, 'packages', 'dsh-task-board', 'src', 'client')
    await mkdir(targetDir, { recursive: true })
    await writeFile(join(targetDir, 'settings-form.ts'), renderCopy('export const bad = 2' + String.fromCharCode(10), 'settings-form.ts', 'shared/client/settings/settings-form.ts'))

    // checkSync compares all consumers; the missing files count as drift too.
    const before = await checkSync(root)
    assert.ok(before.some(entry => entry.reason === 'content drifted from shared source'))
    assert.ok(before.some(entry => entry.reason === 'missing'))

    await applySync(root)
    const after = await checkSync(root)
    assert.deepEqual(after, [])
    const fixed = await readFile(join(targetDir, 'settings-form.ts'), 'utf8')
    assert.equal(stripHeader(fixed, 'settings-form.ts', 'shared/client/settings/settings-form.ts'), sourceText)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('the live tree is in sync', async () => {
  const drift = await checkSync()
  assert.deepEqual(drift, [])
})

/** The clean fixture both orphan tests start from: every source present, every copy rendered in sync. */
async function seedInSyncTree(root) {
  const sourceText = 'export const shared = 1' + String.fromCharCode(10)
  for (const entry of copyEntries(root)) {
    await mkdir(dirname(entry.source), { recursive: true })
    await writeFile(entry.source, sourceText)
  }
  // The real shared/client/settings/settings-entry-form.ts carries a generated
  // header of its own (it was promoted from a copy without stripping it); a
  // manifest source must stay exempt from the orphan sweep even so.
  const selfHeader = '// Generated by scripts/sync-shared.mjs from shared/client/settings/settings-entry-form.ts. Do not edit this copy; edit the shared source and run "node scripts/sync-shared.mjs".'
  await writeFile(join(root, 'shared', 'client', 'settings', 'settings-entry-form.ts'), selfHeader + String.fromCharCode(10) + sourceText)
  await applySync(root)
}

const ORPHAN_FIXTURE = '// Generated by scripts/sync-shared.mjs from shared/host/http.ts. Do not edit this copy; edit the shared source and run "node scripts/sync-shared.mjs".' + String.fromCharCode(10) + 'export const orphan = 1' + String.fromCharCode(10)

test('checkOrphans reports the unlisted header-bearing file at its file:line and nothing else', async () => {
  const root = await mkdtemp(join(tmpdir(), 'sync-shared-orphan-'))
  try {
    await seedInSyncTree(root)
    const orphan = join(root, 'packages', 'dsh-orphan-fixture', 'src', 'host', 'http.ts')
    await mkdir(dirname(orphan), { recursive: true })
    await writeFile(orphan, ORPHAN_FIXTURE)
    // Exactly the unlisted file comes back, at file:line: every in-manifest
    // copy and the self-headed source stay silent.
    assert.deepEqual(await checkOrphans(root), [{ file: 'packages/dsh-orphan-fixture/src/host/http.ts', line: 1 }])
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('the --check CLI exits green on a clean tree and non-zero on drift or an orphan', async () => {
  const root = await mkdtemp(join(tmpdir(), 'sync-shared-orphan-cli-'))
  try {
    await seedInSyncTree(root)
    const env = { ...process.env, SYNC_SHARED_ROOT: root }
    const script = fileURLToPath(new URL('./sync-shared.mjs', import.meta.url))
    const runCheck = () => spawnSync(process.execPath, [script, '--check'], { env, encoding: 'utf8' })

    const clean = runCheck()
    assert.equal(clean.status, 0, clean.stderr)
    assert.match(clean.stdout, /no orphan generated copies/)

    // The original in-manifest drift semantics survive the orphan addition:
    // a target whose body drifted from its source is still reported as drift,
    // before any orphan talk.
    const target = join(root, 'packages', 'dsh-task-board', 'src', 'client', 'settings-form.ts')
    await writeFile(target, headerFor('settings-form.ts', 'shared/client/settings/settings-form.ts') + String.fromCharCode(10) + 'export const drifted = true' + String.fromCharCode(10))
    const drifted = runCheck()
    assert.notEqual(drifted.status, 0)
    assert.match(drifted.stderr, /drift: .*settings-form\.ts \(content drifted from shared source\)/)

    await applySync(root)
    const orphan = join(root, 'packages', 'dsh-orphan-fixture', 'src', 'host', 'http.ts')
    await mkdir(dirname(orphan), { recursive: true })
    await writeFile(orphan, ORPHAN_FIXTURE)
    const dirty = runCheck()
    assert.notEqual(dirty.status, 0)
    assert.match(dirty.stderr, /orphan: packages\/dsh-orphan-fixture\/src\/host\/http\.ts:1/)
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

test('the live tree carries no orphan generated copies', async () => {
  assert.deepEqual(await checkOrphans(), [])
})
